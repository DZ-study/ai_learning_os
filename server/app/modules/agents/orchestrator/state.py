from typing import Any, TypedDict


class OrchestratorState(TypedDict, total=False):
    """
    Global Orchestrator 的 LangGraph Runtime State。

    注意：
    State 是一次 Graph 执行过程中的状态，
    不是数据库里的 AgentSession。
    """

    # --------------------------------------------------
    # Identity
    # --------------------------------------------------

    user_id: str

    session_id: str

    goal_id: str | None

    # --------------------------------------------------
    # Request
    # --------------------------------------------------

    user_input: str | None

    # --------------------------------------------------
    # Workflow
    # --------------------------------------------------

    workflow_id: str

    status: str

    # --------------------------------------------------
    # Current Worker
    # --------------------------------------------------

    current_agent: str | None

    # --------------------------------------------------
    # Worker Result
    # --------------------------------------------------

    worker_result: dict[str, Any] | None

    # --------------------------------------------------
    # Orchestrator Decision
    # --------------------------------------------------

    decision: dict[str, Any] | None

    # --------------------------------------------------
    # Runtime Context
    # --------------------------------------------------

    context: dict[str, Any]

    # --------------------------------------------------
    # Human-in-the-loop
    # --------------------------------------------------

    awaiting_user: bool

    # --------------------------------------------------
    # Response
    # --------------------------------------------------

    response: dict[str, Any] | None

    # --------------------------------------------------
    # Error
    # --------------------------------------------------

    error: dict[str, Any] | None
